    64141, 64171, 64200, 64230, 64259, 64288, 64318, 64348, 64377, 64407, 64436, 64466,  // 1499 AH
    64496, 64525, 64555, 64584, 64614, 64643, 64672, 64702, 64731, 64761, 64790, 64820,  // 1500 AH
    )

    private fun gregorianToJd(y: Int, m: Int, d: Int): Int {
        val a = (14 - m) / 12
        val yy = y + 4800 - a
        val mm = m + 12 * a - 3
        return d + (153 * mm + 2) / 5 + 365 * yy + yy / 4 - yy / 100 + yy / 400 - 32045
    }

    private fun tabular(y: Int, m: Int, d: Int): Triple<Int, Int, Int> {
        val jd = gregorianToJd(y, m, d)
        val l = jd - 1948440 + 10632
        val n = (l - 1) / 10631
        val rem = l - 10631 * n + 354
        val j = ((10985 - rem) / 5316) * ((50 * rem) / 17719) +
            (rem / 5670) * ((43 * rem) / 15238)
        val l2 = rem - ((30 - j) / 15) * ((17719 * j) / 50) -
            (j / 16) * ((15238 * j) / 43) + 29
        val hm = (24 * l2) / 709
        val hd = l2 - (709 * hm) / 24
        val hy = 30 * n + j - 30
        return Triple(hy, hm, hd)
    }

    /** -> (hijriYear, hijriMonth, hijriDay) for a Gregorian date. */
    fun fromGregorian(year: Int, month: Int, day: Int): Triple<Int, Int, Int> {
        val jd = gregorianToJd(year, month, day)
        // binary search: last month start <= jd
        var lo = 0
        var hi = MONTH_OFFSETS.size - 1
        var idx = -1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            if (K_BASE_JD + MONTH_OFFSETS[mid] <= jd) {
                idx = mid
                lo = mid + 1
            } else {
                hi = mid - 1
            }
        }
        if (idx >= 0 && idx < MONTH_OFFSETS.size) {
            val dayNum = jd - (K_BASE_JD + MONTH_OFFSETS[idx]) + 1
            if (dayNum in 1..31) {
                return Triple(FIRST_YEAR + idx / 12, idx % 12 + 1, dayNum)
            }
        }
        return tabular(year, month, day)
    }

    /** Days in a Hijri month (29/30) from the same table. */
    fun daysInMonth(hyear: Int, hmonth: Int): Int {
        val idx = (hyear - FIRST_YEAR) * 12 + (hmonth - 1)
        return if (idx >= 0 && idx + 1 < MONTH_OFFSETS.size) {
            MONTH_OFFSETS[idx + 1] - MONTH_OFFSETS[idx]
        } else {
            if (hmonth % 2 == 1) 30 else 29
        }
    }
