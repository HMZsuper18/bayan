/// Hijri date conversion using the official KACST Umm al-Qura tables.
///
/// The month-start data is embedded directly from the ICU islamic-umalqura
/// calendar (sourced from ummalquracalendar.org, CC BY 4.0).  Every
/// conversion is an O(log n) binary search — no floating-point astronomy.
///
/// Covers 1 Muharram 1318 AH (1900-04-30) through 30 Dhu al-Hijjah 1500 AH
/// (2077-11-16).  Dates outside this range fall back to the Kuwaiti tabular
/// algorithm (±1-2 days).
