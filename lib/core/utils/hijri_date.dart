  const HijriDate._(this.year, this.month, this.day);

  int operator [](int index) {
    switch (index) {
      case 0: return year;
      case 1: return month;
      case 2: return day;
      default: throw RangeError.index(index, this, 'index', null, 3);
    }
  }

  static HijriDate today() {
    final now = DateTime.now();
    final hd = fromGregorian(now.year, now.month, now.day);
    return HijriDate._(hd[0], hd[1], hd[2]);
  }

  /// Converts a Gregorian [year], [month], [day] to Hijri [year, month, day].
  /// Uses embedded Umm al-Qura tables for 1318–1500 AH (exact).
  /// Falls back to the Kuwaiti tabular algorithm outside that range.
  static List<int> fromGregorian(int year, int month, int day) {
    final jd = _gregorianToJulian(year, month, day);
    var lo = 0;
    var hi = _kMonthOffsets.length;
    while (lo < hi) {
      final mid = (lo + hi) ~/ 2;
      if (_kBaseJd + _kMonthOffsets[mid] <= jd) {
        lo = mid + 1;
      } else {
        hi = mid;
      }
    }
    final idx = lo - 1;
    if (idx >= 0 && idx < _kMonthOffsets.length) {
      final monthStartJd = _kBaseJd + _kMonthOffsets[idx];
      final dayNum = jd - monthStartJd + 1;
      final hYear = 1318 + idx ~/ 12;
      final hMonth = idx % 12 + 1;
      return [hYear, hMonth, dayNum];
    }
    return _fromGregorianTabular(year, month, day);
  }

  static List<int> toGregorian(int hYear, int hMonth, int hDay) {
    final idx = (hYear - 1318) * 12 + (hMonth - 1);
    if (idx >= 0 && idx < _kMonthOffsets.length) {
      final monthStartJd = _kBaseJd + _kMonthOffsets[idx];
      final targetJd = monthStartJd + hDay - 1;
      return _julianToGregorian(targetJd);
    }
    return _toGregorianTabular(hYear, hMonth, hDay);
  }

  static int daysInHijriMonth(int year, int month) {
    final idx = (year - 1318) * 12 + (month - 1);
    if (idx >= 0 && idx + 1 < _kMonthOffsets.length) {
      return _kMonthOffsets[idx + 1] - _kMonthOffsets[idx];
    }
    return (month.isOdd) ? 30 : 29;
  }

  static String monthName(int month, {String? locale}) {
    final m = month - 1;
    if (locale == 'ar') return _monthNamesAr[m];
    if (locale == 'ur') return _monthNamesUr[m];
    return _monthNamesEn[m];
  }

  // --- Kuwaiti tabular fallback (±1-2 days, for dates outside table range) ---

  static List<int> _fromGregorianTabular(int year, int month, int day) {
    final jd = _gregorianToJulian(year, month, day);
    final l = jd - 1948440 + 10632;
    final n = ((l - 1) / 10631).floor();
    final remainder = l - 10631 * n + 354;
    final j = ((10985 - remainder) / 5316).floor() *
            ((50 * remainder) / 17719).floor() +
        (remainder / 5670).floor() * ((43 * remainder) / 15238).floor();
    final l2 = remainder -
        ((30 - j) / 15).floor() * ((17719 * j) / 50).floor() -
        (j / 16).floor() * ((15238 * j) / 43).floor() + 29;
    final hm = ((24 * l2) / 709).floor();
    final hd = l2 - ((709 * hm) / 24).floor();
    final hy = 30 * n + j - 30;
    return [hy, hm, hd];
  }

  static List<int> _toGregorianTabular(int hYear, int hMonth, int hDay) {
    final jd = ((11 * hYear + 3) / 30).floor() +
        354 * hYear + 30 * hMonth -
        ((9 * hYear + 2) / 30).floor() + hDay + 1948440 - 385;
    return _julianToGregorian(jd);
  }

  static int _gregorianToJulian(int y, int m, int d) {
    final a = ((14 - m) / 12).floor();
    final yy = y + 4800 - a;
    final mm = m + 12 * a - 3;
    return d + ((153 * mm + 2) / 5).floor() + 365 * yy +
        (yy / 4).floor() - (yy / 100).floor() + (yy / 400).floor() - 32045;
  }

  static List<int> _julianToGregorian(int jd) {
    final l = jd + 68569;
    final n = ((4 * l) / 146097).floor();
    final l2 = l - ((146097 * n + 3) / 4).floor();
    final i = ((4000 * (l2 + 1)) / 1461001).floor();
    final l3 = l2 - ((1461 * i) / 4).floor() + 31;
    final j = ((80 * l3) / 2447).floor();
    final day = l3 - ((2447 * j) / 80).floor();
    final l4 = (j / 11).floor();
    final month = j + 2 - 12 * l4;
    final year = 100 * (n - 49) + i + l4;
    return [year, month, day];
  }

